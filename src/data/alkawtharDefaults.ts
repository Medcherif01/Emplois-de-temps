type DayMatrix = Record<DayOfWeek, Array<[string, string, string?, string?] | null>>;

function buildSlots(matrix: DayMatrix): Record<string, LessonSlot> {
  const slots: Record<string, LessonSlot> = {};
  for (const day of DAYS_OF_WEEK) {
    const dayArr = matrix[day] || [];
    dayArr.forEach((cell, idx) => {
      if (!cell) return;
      const period = idx + 1;
      const [subject, teacher, subSubject, subTeacher] = cell;
      const slot: LessonSlot = { subject, teacher };
      if (subSubject && subTeacher) {
        slot.subSubject = subSubject;
        slot.subTeacher = subTeacher;
      }
      slots[`${day}_${period}`] = slot;
    });
  }
  return slots;
}

