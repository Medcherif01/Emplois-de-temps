export function teacherMatchesSlot(teacherName: string, slotTeacher: string): boolean {
  if (!teacherName || !slotTeacher) return false;
  if (slotTeacher.trim().toLowerCase() === teacherName.trim().toLowerCase()) {
    return true;
  }
  const parts = slotTeacher
    .split(/[\/&+]/)
    .map((s) => s.trim().toLowerCase())
    .filter(Boolean);
  return parts.includes(teacherName.trim().toLowerCase());
}

export function buildTeacherTimetable(
  teacherName: string,
  classes: SchoolClass[]
): {
  slots: Record<string, LessonSlot>;
  totalPeriods: number;
  classesTaught: string[];
} {
  const slots: Record<string, LessonSlot> = {};
  const classesSet = new Set<string>();
  let totalPeriods = 0;

  for (const cls of classes) {
    for (const [key, slot] of Object.entries(cls.slots)) {
      const matchPrimary = teacherMatchesSlot(teacherName, slot.teacher);
      const matchSub =
        slot.subTeacher && teacherMatchesSlot(teacherName, slot.subTeacher);

      if (matchPrimary || matchSub) {
        totalPeriods += 1;
        classesSet.add(cls.name);
        const subj = matchPrimary ? slot.subject : slot.subSubject || slot.subject;
        if (!slots[key]) {
          slots[key] = {
            subject: subj,
            teacher: slot.jointWithClasses?.length
              ? `${cls.name} + ${slot.jointWithClasses.join(' + ')}`
              : cls.name,
            room: slot.room || cls.room,
            jointWithClasses: slot.jointWithClasses,
            isIntercalated: slot.isIntercalated || Boolean(slot.subSubject && slot.subTeacher),
          };
        } else {
          // If it's an intentional joint class, merge class names cleanly without counting twice in display
          const isJoint = slot.jointWithClasses?.some(
            (jc) => jc.toLowerCase() === slots[key].teacher.toLowerCase()
          );
          if (isJoint) {
            totalPeriods = Math.max(1, totalPeriods - 1); // Joint class is 1 period of teaching load
          } else {
            slots[key] = {
              ...slots[key],
              subSubject: subj,
              subTeacher: cls.name,
              isIntercalated: true,
            };
          }
        }
      }
    }
  }

  return {
    slots,
    totalPeriods,
    classesTaught: Array.from(classesSet),
  };
}

export function detectScheduleConflicts(
  classes: SchoolClass[],
  teachers: TeacherProfile[]
): ScheduleConflict[] {
  const conflicts: ScheduleConflict[] = [];
  const teacherByName = new Map<string, TeacherProfile>();
  teachers.forEach((t) => teacherByName.set(t.name.toLowerCase(), t));

  // Track (teacherName, day_period) -> list of { className, jointWithClasses }
  const occupancy = new Map<
    string,
    {
      teacher: string;
      day: DayOfWeek;
      period: number;
      classes: string[];
      jointPairs: Set<string>;
    }
  >();

  for (const cls of classes) {
    for (const [key, slot] of Object.entries(cls.slots)) {
      const [dayStr, periodStr] = key.split('_');
      const day = dayStr as DayOfWeek;
      const period = Number(periodStr);

      const checkTeacher = (tName?: string) => {
        if (!tName) return;
        const clean = tName.trim();
        if (!clean) return;
        const occKey = `${clean.toLowerCase()}__${key}`;
        if (!occupancy.has(occKey)) {
          occupancy.set(occKey, {
            teacher: clean,
            day,
            period,
            classes: [],
            jointPairs: new Set(),
          });
        }
        const entry = occupancy.get(occKey)!;
        entry.classes.push(cls.name);
        if (slot.jointWithClasses?.length) {
          for (const jc of slot.jointWithClasses) {
            const pairKey = [cls.name.toLowerCase(), jc.toLowerCase()]
              .sort()
              .join('::');
            entry.jointPairs.add(pairKey);
          }
        }

        // Check teacher unavailability
        const profile = teacherByName.get(clean.toLowerCase());
        if (profile && profile.unavailableSlots.includes(key)) {
          conflicts.push({
            id: `unavail_${profile.id}_${cls.id}_${key}`,
            type: 'unavailable_slot',
            severity: 'critical',
            teacher: clean,
            day,
            period,
            classesInvolved: [cls.name],
            description: `${clean} est marqué(e) indisponible le ${day} (Période ${period}) mais enseigne en ${cls.name}.`,
          });
        }
      };

      checkTeacher(slot.teacher);
      if (slot.subTeacher) checkTeacher(slot.subTeacher);
    }
  }

  for (const [occKey, item] of occupancy.entries()) {
    if (item.classes.length > 1) {
      // Check if all classes in this slot are intentionally assembled together (jointWithClasses)
      let allIntentionallyJoint = false;
      if (item.classes.length === 2) {
        const pairKey = [
          item.classes[0].toLowerCase(),
          item.classes[1].toLowerCase(),
        ]
          .sort()
          .join('::');
        if (item.jointPairs.has(pairKey)) {
          allIntentionallyJoint = true;
        }
      }
      if (allIntentionallyJoint) continue;

      const isSharedMontessori = item.teacher.includes('Fatimah');
      conflicts.push({
        id: `dbl_${occKey}`,
        type: 'double_booking',
        severity: isSharedMontessori ? 'warning' : 'critical',
        teacher: item.teacher,
        day: item.day,
        period: item.period,
        classesInvolved: item.classes,
        description: `${item.teacher} est affecté(e) simultanément dans ${item.classes.join(' & ')} le ${item.day} (Période ${item.period}).`,
      });
    }
  }

  return conflicts;
}
